// Declarar uma váriavel chamada contador que recebe um valor numérico
let contador = 0

// Enquanto  contador for menor ou igual a 10, repita
while (contador <= 10) {
    console.log("olha a hora do café");
    console.log("venha tomar seu café");
    console.log("café da manhã da tarde, NÃO IMPORTA!");
    console.log("VENHA TOMAR SEU CAFÉ!!!");

    // Adicionar ++ após o nome de uma váriavel faz com que seja adicionado 1 ao seu valor
    contador++
    console.log(contador);
}