// Para utilizar o for é necessário ter um contador para que delimitemos a quntidade de vezes que algo será repetindo. A estrutura da for recebe inicialização, condição e incremento

console.log("Vou contar até 10 e depois dizer morango");

//  inicialização   condição    incremento 
for (let i = 1;      i <= 10;    i += 2) {
    console.log(i);
}

console.log("morango!!!");